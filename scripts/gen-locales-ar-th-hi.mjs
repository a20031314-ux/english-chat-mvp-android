function pack(overrides, name) {
  const missing = Object.keys(en).filter((k) => !(k in overrides));
  const extra = Object.keys(overrides).filter((k) => !(k in en));
  if (missing.length || extra.length) {
    throw new Error(
      `${name}: missing ${missing.length} [${missing.slice(0, 30).join(", ")}] extra ${extra.length} [${extra.slice(0, 10).join(", ")}]`,
    );
  }
  if (Object.keys(overrides).length !== Object.keys(en).length) {
    throw new Error(
      `${name}: override count ${Object.keys(overrides).length} != en ${Object.keys(en).length}`,
    );
  }
  return { ...en, ...overrides };
}

function placeholders(s) {
  return [...String(s).matchAll(/\{[a-zA-Z]+\}/g)].map((m) => m[0]);
}

function isPlaceholderOnly(s) {
  return String(s).replace(/\{[a-zA-Z]+\}/g, "").replace(/[\s./\-−~·]/g, "") === "";
}

const BRAND_EXACT = new Set([
  "BBC",
  "Reddit",
  "Guardian",
  "YouTube",
  "PDF",
  "EPUB",
  "TXT",
  "AI",
  "Vlog",
]);

const EMOJI_RE = /✔|🔁|🗑|🆕|✅|💡|👍|✓|🎯/g;

function assertLocale(name, locale) {
  if (Object.keys(locale).length !== Object.keys(en).length) {
    throw new Error(
      `${name}: key count ${Object.keys(locale).length} != en ${Object.keys(en).length}`,
    );
  }
  const leftover = [];
  for (const key of Object.keys(en)) {
    const src = en[key];
    const val = locale[key];
    const srcPh = [...placeholders(src)].sort().join(",");
    const valPh = [...placeholders(val)].sort().join(",");
    if (srcPh !== valPh) {
      throw new Error(`${name}.${key}: placeholder mismatch ${srcPh} vs ${valPh}`);
    }
    const srcEmoji = (src.match(EMOJI_RE) || []).join("");
    const valEmoji = (val.match(EMOJI_RE) || []).join("");
    if (srcEmoji !== valEmoji) {
      throw new Error(`${name}.${key}: emoji mismatch ${srcEmoji} vs ${valEmoji}`);
    }
    if (val === src) {
      const trimmed = String(src).trim();
      if (BRAND_EXACT.has(trimmed) || isPlaceholderOnly(src)) continue;
      leftover.push(key);
    }
  }
  return leftover;
}

