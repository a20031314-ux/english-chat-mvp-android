/** 앱 언어의 문구. 빠진 키는 영어로(copy.test.ts가 빠짐을 막는다). */
export function roomCopy(locale: string): RoomCopy {
  if (locale === "ko") return ko;
  const local = ROOM_COPY_LOCALES[locale];
  return local ? ({ ...en, ...local } as RoomCopy) : en;
}

