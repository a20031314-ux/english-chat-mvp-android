export const ICON_COPY_LOCALES = ["ko", "en", ...Object.keys(LOCALES)];
export const ICON_COPY_KEYS = Object.keys(en) as (keyof IconCopy)[];

export function iconCopy(locale: string): IconCopy {
  if (locale === "ko") return ko;
  return LOCALES[locale] ?? en;
}

/** 서버 오류 코드 → 문구. */
export function iconErrorText(t: IconCopy, code: string): string {
  const map: Record<string, string> = {
    TOO_NEW: t.tooNew,
    TOO_BIG: t.tooBig,
    BAD_TYPE: t.badType,
    TOO_MANY_FRAMES: t.tooManyFrames,
    REJECTED: t.rejected,
    FULL: t.full,
    LIMIT: t.limit,
  };
  return map[code] ?? t.failed;
}

