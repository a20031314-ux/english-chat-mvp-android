export const INVITE_COPY_LOCALES = ["ko", "en", ...Object.keys(LOCALES)];

export function inviteCopy(locale: string): InviteCopy {
  if (locale === "ko") return ko;
  return LOCALES[locale] ?? en;
}

/** {name}·{room}·{n}·{p}·{a}·{b}·{plan}·{date}·{days}·{plus}·{premium} 채우기. 넣은 값 안의 {…}는 다시 바꾸지 않는다. */
export function fillInvite(text: string, values: Record<string, string | number | undefined>): string {
  return text.replace(/\{(\w+)\}/g, (whole, key: string) => (key in values ? String(values[key] ?? "") : whole));
}

