export const INVITE_COPY_LOCALES = ["ko", "en", ...Object.keys(LOCALES)];

export function inviteCopy(locale: string): InviteCopy {
  if (locale === "ko") return ko;
  return LOCALES[locale] ?? en;
}

/** "{name}"·"{room}"·"{n}" 채우기. 이름에 들어간 {…}는 다시 바꾸지 않는다. */
export function fillInvite(text: string, values: { name?: string; room?: string; n?: number }): string {
  return text.replace(/\{(name|room|n)\}/g, (_, key: "name" | "room" | "n") => String(values[key] ?? ""));
}

