function toKatakana(text: string): string {
  return Array.from(text)
    .map((ch) => {
      const code = ch.codePointAt(0);
      if (code && code >= 0x3041 && code <= 0x3096) {
        return String.fromCodePoint(code + 0x60);
      }
      return ch;
    })
    .join("");
}

