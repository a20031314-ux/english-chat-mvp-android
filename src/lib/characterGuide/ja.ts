function kanaItems(
  rows: KanaRow[],
  category: "hiragana" | "katakana",
): CharacterItem[] {
  return rows.map((row) => {
    const katakana = category === "katakana";
    const character = katakana ? toKatakana(row.char) : row.char;
    const examples = katakana
      ? KATAKANA_EXAMPLES[character] ?? []
      : row.examples;
    return {
      id: `ja-${category}-${row.reading}-${character}`,
      character,
      reading: row.reading,
      pronunciation: row.reading,
      category,
      examples,
    };
  });
}

